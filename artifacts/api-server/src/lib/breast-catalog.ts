const localized = ["Neoadjuvant", "Adjuvant", "Post-neoadjuvant"];
function regimen(name: string, settings: string[], phases = ["Induction", "Other"], subtypes = ["HER2-positive / HR-negative"], note?: string) {
  return { name, settings, phases, subtypes, ...(note ? { note } : {}) };
}
function tripleNegative(name: string, settings: string[], note?: string) {
  return regimen(name, settings, ["Induction", "Other"], ["Triple-negative"], note);
}
